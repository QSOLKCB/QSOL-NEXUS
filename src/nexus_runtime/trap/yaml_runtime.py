_TRAP_REF = re.compile(r"^trap:[0-9a-f]{64}$")


class TrapYAMLRuntimeError(ValueError):
    """A deterministic interpreter failure with a stable error code."""

    def __init__(self, code: str, message: str) -> None:
        self.code = code
        super().__init__(message)


def _runtime_error(code: str, message: str) -> None:
    raise TrapYAMLRuntimeError(code, message)


def _json_copy(value: Any) -> Any:
    try:
        return json.loads(canonical_json(value))
    except (TypeError, ValueError, OverflowError, RecursionError) as exc:
        raise TrapYAMLRuntimeError(
            "trap_yaml_invalid_fixture",
            "synthetic fixture must contain bounded JSON primitives",
        ) from exc


def _freeze(value: Any) -> Any:
    if type(value) is dict:
        return MappingProxyType({key: _freeze(child) for key, child in value.items()})
    if type(value) is list:
        return tuple(_freeze(child) for child in value)
    return value


def _thaw(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {str(key): _thaw(child) for key, child in value.items()}
    if isinstance(value, tuple):
        return [_thaw(child) for child in value]
    if isinstance(value, list):
        return [_thaw(child) for child in value]
    return value


@dataclass(frozen=True)
class TrapFixture:
    fixture_id: str
    payload: Mapping[str, Any]

    def to_dict(self) -> dict[str, Any]:
        return _thaw(self.payload)


def _make_fixture(fixture_id: str, payload: Mapping[str, Any]) -> TrapFixture:
    copied = _json_copy({"fixture_id": fixture_id, **dict(payload)})
    return TrapFixture(fixture_id, _freeze(copied))


